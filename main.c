uint16_t _foundHeader(uint8_t *pHeader) {
    if ( pHeader == NULL ) { return 0; }
    frame_header_t *pFrameHeader = (frame_header_t*)( pHeader );
    return 
      sizeof(frame_header_t) + pFrameHeader->payloadLength + PROT_SYNC_END_LEN;
}



#define PROT_HEADER_LEN (PROT_SYNC_START_LEN + 2)
#define PROT_MAX_PAYLOAD_LEN 100

typedef struct {
    uint8_t     syncStart   [PROT_SYNC_START_LEN];
    uint16_t    payloadLength;
} frame_header_t;

typedef struct {
    frame_header_t  header;
    uint8_t         payload[PROT_MAX_PAYLOAD_LEN];
    uint8_t         syncEnd[PROT_SYNC_END_LEN];
} frame_t;

